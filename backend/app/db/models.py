"""SQLAlchemy 2 ORM models backing the SKYGYM database.

Table set is fixed by the specification: users, scenarios, sessions, actions,
events, scores, skills_history, habit_features, bandit_state.

All JSON-shaped columns are stored as JSON so that the database stays trivially
portable and schema-version-tagged.
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Any

from sqlalchemy import (
    JSON,
    Boolean,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    UniqueConstraint,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


def _utcnow() -> datetime:
    """Return an aware UTC timestamp (the simulation core never uses wall time)."""
    return datetime.now(UTC)


class Base(DeclarativeBase):
    """Declarative base for every SKYGYM table."""


class UnitRow(Base):
    """A cohort of trainees used by the unit dashboard."""

    __tablename__ = "units"

    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    name: Mapped[str] = mapped_column(String(160), nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=_utcnow)


class User(Base):
    """A trainee or instructor."""

    __tablename__ = "users"

    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    display_name: Mapped[str] = mapped_column(String(120), nullable=False)
    role: Mapped[str] = mapped_column(String(32), nullable=False, default="trainee")
    unit_id: Mapped[str | None] = mapped_column(String(64), nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=_utcnow)
    synthetic: Mapped[bool] = mapped_column(Boolean, default=False)

    sessions: Mapped[list[SessionRow]] = relationship(back_populates="user")

    __table_args__ = (Index("ix_users_unit", "unit_id"),)


class ScenarioRow(Base):
    """A stored scenario: shipped, generated by an instructor, or built from NL."""

    __tablename__ = "scenarios"

    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    name: Mapped[str] = mapped_column(String(200), nullable=False)
    schema_version: Mapped[int] = mapped_column(Integer, nullable=False)
    seed: Mapped[int] = mapped_column(Integer, nullable=False)
    difficulty_json: Mapped[JSON] = mapped_column(JSON, nullable=False)
    tags_json: Mapped[JSON] = mapped_column(JSON, nullable=False)
    body_json: Mapped[JSON] = mapped_column(JSON, nullable=False)
    source: Mapped[str] = mapped_column(String(32), nullable=False, default="shipped")
    created_by: Mapped[str | None] = mapped_column(String(64), ForeignKey("users.id"))
    created_at: Mapped[datetime] = mapped_column(DateTime, default=_utcnow)
    oracle_score: Mapped[float | None] = mapped_column(Float, nullable=True)

    __table_args__ = (
        Index("ix_scenarios_source", "source"),
        Index("ix_scenarios_seed", "seed"),
    )


class SessionRow(Base):
    """One trainee run of one scenario."""

    __tablename__ = "sessions"

    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    scenario_id: Mapped[str] = mapped_column(String(64), ForeignKey("scenarios.id"))
    user_id: Mapped[str] = mapped_column(String(64), ForeignKey("users.id"))
    seed: Mapped[int] = mapped_column(Integer, nullable=False)
    bandit_state_json: Mapped[JSON | None] = mapped_column(JSON, nullable=True)
    started_at: Mapped[datetime] = mapped_column(DateTime, default=_utcnow)
    ended_at: Mapped[datetime | None] = mapped_column(DateTime, nullable=True)
    final_state_hash: Mapped[str | None] = mapped_column(String(64), nullable=True)
    total_score: Mapped[float | None] = mapped_column(Float, nullable=True)
    aborted: Mapped[bool] = mapped_column(Boolean, default=False)
    synthetic: Mapped[bool] = mapped_column(Boolean, default=False)
    team_json: Mapped[JSON | None] = mapped_column(JSON, nullable=True)

    user: Mapped[User] = relationship(back_populates="sessions")
    actions: Mapped[list[ActionRow]] = relationship(
        back_populates="session", cascade="all, delete-orphan"
    )
    events: Mapped[list[EventRow]] = relationship(
        back_populates="session", cascade="all, delete-orphan"
    )

    __table_args__ = (
        Index("ix_sessions_user", "user_id"),
        Index("ix_sessions_scenario", "scenario_id"),
    )


class ActionRow(Base):
    """A single trainee action; the determinism contract is the ordered log."""

    __tablename__ = "actions"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    session_id: Mapped[str] = mapped_column(String(64), ForeignKey("sessions.id"))
    seq: Mapped[int] = mapped_column(Integer, nullable=False)
    t: Mapped[float] = mapped_column(Float, nullable=False)
    type: Mapped[str] = mapped_column(String(32), nullable=False)
    track_id: Mapped[str | None] = mapped_column(String(48), nullable=True)
    params_json: Mapped[JSON] = mapped_column(JSON, nullable=False)
    source: Mapped[str] = mapped_column(String(24), nullable=False, default="trainee")

    session: Mapped[SessionRow] = relationship(back_populates="actions")

    __table_args__ = (
        UniqueConstraint("session_id", "seq", name="uq_actions_session_seq"),
        Index("ix_actions_session_t", "session_id", "t"),
    )


class EventRow(Base):
    """A simulation event (spawn, sensor failure, engagement result, ...)."""

    __tablename__ = "events"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    session_id: Mapped[str] = mapped_column(String(64), ForeignKey("sessions.id"))
    t: Mapped[float] = mapped_column(Float, nullable=False)
    kind: Mapped[str] = mapped_column(String(48), nullable=False)
    entity_id: Mapped[str | None] = mapped_column(String(48), nullable=True)
    track_id: Mapped[str | None] = mapped_column(String(48), nullable=True)
    data_json: Mapped[JSON] = mapped_column(JSON, nullable=False)

    session: Mapped[SessionRow] = relationship(back_populates="events")

    __table_args__ = (Index("ix_events_session_t", "session_id", "t"),)


class ScoreRow(Base):
    """The full score breakdown of a session."""

    __tablename__ = "scores"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    session_id: Mapped[str] = mapped_column(String(64), ForeignKey("sessions.id"))
    total: Mapped[float] = mapped_column(Float, nullable=False)
    detection: Mapped[float] = mapped_column(Float, nullable=False)
    classification: Mapped[float] = mapped_column(Float, nullable=False)
    prioritisation: Mapped[float] = mapped_column(Float, nullable=False)
    engagement: Mapped[float] = mapped_column(Float, nullable=False)
    workload: Mapped[float] = mapped_column(Float, nullable=False)
    breakdown_json: Mapped[JSON] = mapped_column(JSON, nullable=False)

    __table_args__ = (Index("ix_scores_total", "total"),)


class SkillHistoryRow(Base):
    """Skill ratings after every session, for the dashboard trend charts."""

    __tablename__ = "skills_history"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    user_id: Mapped[str] = mapped_column(String(64), ForeignKey("users.id"))
    session_id: Mapped[str] = mapped_column(String(64), ForeignKey("sessions.id"))
    detection: Mapped[float] = mapped_column(Float, nullable=False)
    classification: Mapped[float] = mapped_column(Float, nullable=False)
    prioritisation: Mapped[float] = mapped_column(Float, nullable=False)
    engagement: Mapped[float] = mapped_column(Float, nullable=False)
    roe: Mapped[float] = mapped_column(Float, nullable=False)
    difficulty_norm: Mapped[float] = mapped_column(Float, nullable=False)
    recorded_at: Mapped[datetime] = mapped_column(DateTime, default=_utcnow)

    __table_args__ = (Index("ix_skills_user_time", "user_id", "recorded_at"),)


class HabitFeatureRow(Base):
    """Latest per-trainee habit feature vector consumed by the Red Brain.

    One row per trainee: the primary key is the user id, so an upsert replaces
    the previous snapshot rather than growing a history the bandit must scan.
    """

    __tablename__ = "habit_features"

    user_id: Mapped[str] = mapped_column(String(64), ForeignKey("users.id"), primary_key=True)
    session_id: Mapped[str | None] = mapped_column(String(64), nullable=True)
    features_json: Mapped[JSON] = mapped_column(JSON, nullable=False)
    recorded_at: Mapped[datetime] = mapped_column(DateTime, default=_utcnow)

    __table_args__ = (Index("ix_habits_user_time", "user_id", "recorded_at"),)


class BanditStateRow(Base):
    """Snapshot of the Red Brain contextual bandit (LinUCB) state per trainee."""

    __tablename__ = "bandit_state"

    user_id: Mapped[str] = mapped_column(String(64), primary_key=True)
    arms_json: Mapped[JSON] = mapped_column(JSON, nullable=False)
    state_json: Mapped[JSON] = mapped_column(JSON, nullable=False)
    updated_at: Mapped[datetime] = mapped_column(DateTime, default=_utcnow)
    pulls: Mapped[int] = mapped_column(Integer, default=0)


def row_to_dict(row: Any) -> dict[str, Any]:
    """Convert an ORM instance into a plain JSON-serialisable dict."""
    out: dict[str, Any] = {}
    for col in row.__table__.columns:
        value = getattr(row, col.name)
        out[col.name] = value.isoformat() if isinstance(value, datetime) else value
    return out


